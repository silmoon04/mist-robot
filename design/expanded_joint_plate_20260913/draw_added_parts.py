def label(name):
    if name.startswith('08_'):return 'Lower yaw support arm'
    if name.startswith('09_'):return 'Pan-foot spacer, 4 mm'
    spec=importlib.util.spec_from_file_location('mapnames',THIRD/'render_plate_map.py')
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
    return m.short_name(name)


def plate_map():
    p=HERE/'expanded_plate_validation.json';data=json.loads(p.read_text())
    fig=plt.figure(figsize=(12,8.5),facecolor=draw.BG)
    ax=fig.add_axes([.055,.40,.90,.45]);ax.set_aspect('equal')
    ax.set_xlim(5,220);ax.set_ylim(55,175);ax.set_xlabel('Bed X (mm)');ax.set_ylabel('Bed Y (mm)')
    ax.grid(alpha=.15);ax.spines[['top','right']].set_visible(False)
    lines=[]
    for i,pos in enumerate(data['plate']['positions'],1):
        part=next(x for x in data['parts'] if x['name']==pos['name'])
        mesh=trimesh.load_mesh(HERE/part['print_stl'])
        mesh.apply_translation(-mesh.bounds[0]);mesh.apply_translation(pos['bounds_mm'][0])
        mask=mesh.face_normals[:,2]>.0001;tri=mesh.triangles[mask];norm=mesh.face_normals[mask]
        order=np.argsort(tri[:,:,2].mean(axis=1));tri=tri[order];norm=norm[order]
        color=np.array([.78,.52,.18,1]) if part['extra'] else np.array([.10,.52,.54,1])
        colors=np.tile(color,(len(tri),1));colors[:,:3]*=(.75+.25*norm[:,2])[:,None]
        ax.add_collection(PolyCollection(tri[:,:,:2],facecolors=colors,edgecolors='none'))
        b=np.array(pos['bounds_mm']);ax.text(b[:,0].mean(),b[1,1]+2,str(i),ha='center',va='bottom',fontsize=9,weight='bold')
        lines.append(f'{i:02d}  {label(pos["name"])}');pos['map_number']=i
    fig.text(.055,.94,'Expanded plate: 19 parts',fontsize=23,weight='bold',color=draw.INK)
    fig.text(.055,.895,'Teal: the original 14 pieces. Gold: five additions. Keep spacers labelled after removal.',fontsize=11,color=draw.MUTED)
    for i,line in enumerate(lines):
        col=i//5;row=i%5
        fig.text(.055+col*.24,.30-row*.043,line,fontsize=9.3,color=draw.INK)
    fig.text(.055,.045,'Actual mesh top view. Brims are generated by Cura and are not shown.',fontsize=9,color=draw.MUTED)
    fig.savefig(HERE/'expanded_plate_map.png',dpi=160);plt.close(fig)
    p.write_text(json.dumps(data,indent=2),encoding='utf-8')


if __name__=='__main__':image5();plate_map();print('Added assembly sheet and 19-part map rendered.')
