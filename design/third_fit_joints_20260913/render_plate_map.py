"""Render a labelled top view from the actual packed triangle meshes."""
from pathlib import Path
import json
import numpy as np
import trimesh
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.collections import PolyCollection

HERE=Path(__file__).resolve().parent


def short_name(name):
    if 'gauge_no_support' in name:return 'Alignment gauge'
    if 'tie_bolt_spacer' in name:return 'Gauge spacer, 5 mm'
    if 'main_horn_cheek' in name:return 'Main horn cheek'
    if 'auxiliary_horn_cheek' in name:return 'Auxiliary cheek'
    if 'bridge_38' in name:return 'Horn bridge, 38 mm'
    if 'yaw_spacer_nominal' in name:return 'Yaw spacer, 11.6 mm'
    if 'yaw_spacer_short' in name:return 'Yaw sample, 11.3 mm'
    if 'yaw_spacer_long' in name:return 'Yaw sample, 11.9 mm'
    if 'hole_strip' in name:return 'M3 hole strip'
    return 'M3 nut-depth strip'


def main():
    p=HERE/'third_fit_validation.json';d=json.loads(p.read_text())
    scene=trimesh.load(HERE/d['plate']['file'])
    fig=plt.figure(figsize=(11,7.5),facecolor='#fafbf9')
    ax=fig.add_axes([.07,.43,.88,.43]);ax.set_aspect('equal')
    ax.set_xlim(5,220);ax.set_ylim(65,165);ax.set_xlabel('Bed X (mm)');ax.set_ylabel('Bed Y (mm)')
    ax.grid(alpha=.15);ax.spines[['top','right']].set_visible(False)
    labels=[]
    for i,pos in enumerate(d['plate']['positions'],1):
        # Load the source and reproduce its placement, including only a bed-Z rotation.
        source=next(q for q in d['parts'] if q['name']==pos['name'])
        mesh=trimesh.load_mesh(HERE/source['stl'])
        if mesh.extents[0]<mesh.extents[1]:
            mesh.apply_transform(trimesh.transformations.rotation_matrix(np.pi/2,(0,0,1)))
        mesh.apply_translation(-mesh.bounds[0]);mesh.apply_translation(pos['bounds_mm'][0])
        mask=mesh.face_normals[:,2]>.0001
        faces=mesh.triangles[mask];normals=mesh.face_normals[mask]
        order=np.argsort(faces[:,:,2].mean(axis=1));faces=faces[order];normals=normals[order]
        colors=np.tile(np.array([.10,.52,.54,1]),(len(faces),1))
        colors[:,:3]*=(.75+.25*normals[:,2])[:,None]
        ax.add_collection(PolyCollection(faces[:,:,:2],facecolors=colors,edgecolors='none'))
        box=np.array(pos['bounds_mm']);x=box[:,0].mean();y=box[1,1]+2
        ax.text(x,y,str(i),ha='center',va='bottom',fontsize=9,fontweight='bold',color='#283b3d')
        labels.append(f'{i:02d}  {short_name(pos["name"])}')
        pos['map_number']=i
    fig.text(.07,.94,'Next print: joint interfaces',fontsize=22,fontweight='bold',color='#233a3b')
    fig.text(.07,.89,'14 pieces. Keep the arrangement so the small spacers stay identifiable.',fontsize=11)
    for i,label in enumerate(labels):
        col=i//5;row=i%5
        fig.text(.07+col*.305,.32-row*.045,label,fontsize=10,color='#233a3b')
    fig.text(.07,.055,'Top view of actual CAD meshes. Brims are generated by Cura and are not shown.',fontsize=9,color='#617174')
    fig.savefig(HERE/'plate_map.png',dpi=160);plt.close(fig)
    p.write_text(json.dumps(d,indent=2),encoding='utf-8')


if __name__=='__main__':main()
