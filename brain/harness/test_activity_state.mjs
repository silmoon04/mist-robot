import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../duplex/static/activity_state.js',import.meta.url),'utf8');
const {ActivityState}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
let now=0;
const policy=new ActivityState({now:()=>now});
assert.equal(policy.update('listening'),'listening');
assert.equal(policy.update('thinking'),'available','short waits do not flash the symbol');
now=600;assert.equal(policy.update('thinking'),'available');
now=650;assert.equal(policy.update('thinking'),'thinking','a sustained wait becomes visible');
now=900;assert.equal(policy.update('thinking'),'thinking','duplicate events preserve onset');
assert.equal(policy.update('speaking'),'speaking','audible speech immediately removes state thinking');
now=950;assert.equal(policy.update('thinking'),'available','new wait starts a fresh delay');
assert.equal(policy.update('listening'),'listening','interruption never waits for animation');
now=5000;assert.equal(policy.update('listening'),'listening','cancelled pending thinking cannot reappear');
assert.equal(policy.update('checking'),'available');
now=5650;assert.equal(policy.update('checking'),'checking');
assert.equal(policy.update('available'),'available','disconnect clears immediately');
console.log('PASS: short/sustained waits, duplicates, audible speech, interruption and disconnect.');
