// exports.js — turns a sim config into things you can use at the bench:
//  * config JSON (save/load, diffable in the repo)
//  * STS3215 servo table (ticks: 4096/rev, neutral 2048) as C header + JSON
//  * CAD/mass spec sheet (markdown, matches MIST doc style)
//  * bench predictions: kitchen-scale grams per foot, watt-meter amps/watts —
//    falsifiable numbers to calibrate the sim against the real robot at T9.

import { LEG_NAMES } from './config.js';

const TICKS_PER_DEG = 4096 / 360;
const R2D = 180 / Math.PI;
export const JOINT_NAMES = ['hipRoll', 'hipPitch', 'knee', 'wheel'];

// Sign convention: q>0 as defined in kin.js. Servo direction depends on how you
// mount the horn — flip signs[] per joint after the first bench test.
export function servoTable(res) {
  const rows = [];
  let id = 1;
  // Physical build-map order is FL, FR, RR, RL. Keep the analytic arrays in
  // FL, FR, RL, RR order and only reorder rows at this hardware boundary.
  [0, 1, 3, 2].forEach((li) => {
    const leg = res.legs[li];
    for (let j = 0; j < 3; j++) {
      const ratio = j === 2 && res.P.linkage ? res.P.linkRatio : 1;
      const deg = leg.q[j] * R2D * ratio;
      const limits = [res.P.rom.roll, res.P.rom.hip, res.P.rom.knee][j];
      rows.push({
        id, leg: LEG_NAMES[li], joint: JOINT_NAMES[j],
        poseDeg: +deg.toFixed(2),
        tick: Math.round(2048 + deg * TICKS_PER_DEG),
        minTick: Math.round(2048 + limits[0] * R2D * ratio * TICKS_PER_DEG),
        maxTick: Math.round(2048 + limits[1] * R2D * ratio * TICKS_PER_DEG),
      });
      id++;
    }
    rows.push({ id, leg: LEG_NAMES[li], joint: 'wheel', poseDeg: 0, tick: 2048, minTick: 0, maxTick: 4095, wheelMode: true });
    id++;
  });
  return rows;
}

export function servoHeaderC(res) {
  const rows = servoTable(res);
  const lines = [
    '// generated by sim/ — MIST wheeled-quad pose + limits (STS3215, 4096 ticks/rev)',
    '// IDs follow the build map: FL,FR,RR,RL × (hipRoll,hipPitch,knee,wheel).',
    '// Flip SIGN[] entries after bench-checking horn directions. Wheel servos run in wheel mode.',
    '#pragma once',
    '#include <stdint.h>',
    '',
    `#define MIST_NUM_SERVOS ${rows.length}`,
    '',
    'static const uint8_t  MIST_ID[MIST_NUM_SERVOS]      = {' + rows.map((r) => r.id).join(', ') + '};',
    'static const int16_t  MIST_POSE_TICK[MIST_NUM_SERVOS]= {' + rows.map((r) => r.tick).join(', ') + '};',
    'static const int16_t  MIST_MIN_TICK[MIST_NUM_SERVOS] = {' + rows.map((r) => r.minTick).join(', ') + '};',
    'static const int16_t  MIST_MAX_TICK[MIST_NUM_SERVOS] = {' + rows.map((r) => r.maxTick).join(', ') + '};',
    'static const int8_t   MIST_SIGN[MIST_NUM_SERVOS]     = {' + rows.map(() => 1).join(', ') + '};',
    'static const uint8_t  MIST_IS_WHEEL[MIST_NUM_SERVOS] = {' + rows.map((r) => (r.wheelMode ? 1 : 0)).join(', ') + '};',
  ];
  return lines.join('\n');
}

export function specSheetMd(res) {
  const c = res.cfg;
  const mm = (x) => `${Math.round(x)} mm`;
  const massRows = {};
  res.items.forEach((it) => {
    const key = it.group.startsWith('leg') ? `legs (${it.name})` : it.name;
    massRows[key] = (massRows[key] || 0) + it.m * 1000;
  });
  const legTotal = res.items.filter((i) => i.group.startsWith('leg')).reduce((s, i) => s + i.m, 0) * 1000;
  const L = [];
  L.push(`# MIST sim config — spec sheet`);
  L.push('');
  L.push(`Exported from sim/. Total mass **${(res.M * 1000).toFixed(0)} g**, CoM height **${(res.com[2] * 1000).toFixed(0)} mm**, overall verdict **${res.overall.toUpperCase()}**.`);
  L.push('');
  L.push(`## Dimensions (for CAD)`);
  L.push('');
  L.push('| Part | Value |');
  L.push('|---|---|');
  L.push(`| Cylinder | Ø${mm(c.body.cylD)} × ${mm(c.body.cylH)}, shell ${c.body.shellMass} g |`);
  L.push(`| Leg mount height on cylinder | ${mm(c.body.legMountH)} (standoff ${mm(c.body.mountStandoff)}) |`);
  L.push(`| Leg azimuths | front ±${c.geo.frontAz}°, rear ±${c.geo.rearAz}° |`);
  L.push(`| Hip roll→pitch offset (d1) | ${mm(c.leg.d1)} |`);
  L.push(`| Femur / Tibia | ${mm(c.leg.femur)} / ${mm(c.leg.tibia)} (${c.leg.filament}, ${c.leg.beamW}×${c.leg.beamT} mm beam) |`);
  L.push(`| Knee drive | ${c.leg.linkage ? `linkage at hip, ratio ${c.leg.linkRatio}` : 'direct servo at knee'} |`);
  L.push(`| Wheel | Ø${mm(c.wheel.dia)}, ${c.wheel.mass} g |`);
  L.push(`| Wheel drive | ${{ foot: 'hub servo at foot', knee: 'servo at knee, belt down tibia (+' + c.wheel.transMass + ' g stage)', hip: 'servo at hip, belt down femur+tibia (+2×' + c.wheel.transMass + ' g stages)' }[c.wheel.driveMount]} |`);
  L.push(`| Battery position | h=${mm(c.masses.batteryH)}, r=${mm(c.masses.batteryR)}, az=${c.masses.batteryAz}° |`);
  L.push(`| Phone height | ${mm(c.masses.phoneH)} |`);
  L.push('');
  L.push(`## Mass budget (per sim)`);
  L.push('');
  L.push('| Bucket | g |');
  L.push('|---|---:|');
  ['shell', 'battery', 'phone', 'electronics', 'harness', 'headServos', 'payload'].forEach((k) => {
    if (massRows[k]) L.push(`| ${k} | ${massRows[k].toFixed(0)} |`);
  });
  L.push(`| legs total (4× incl. servos+wheels) | ${legTotal.toFixed(0)} |`);
  L.push(`| **total** | **${(res.M * 1000).toFixed(0)}** |`);
  L.push('');
  L.push(`## Verdicts @ this pose`);
  L.push('');
  L.push('| Check | Value | Status |');
  L.push('|---|---|---|');
  res.verdicts.forEach((v) => L.push(`| ${v.label} | ${v.value} | ${v.status.toUpperCase()} — ${v.detail} |`));
  return L.join('\n');
}

export function benchPredictions(res) {
  const L = [];
  L.push(`BENCH PREDICTIONS — verify these before printing legs 2–4 (T9 testbed)`);
  L.push(`Pose: bodyH ${res.cfg.pose.bodyH} mm, stanceR ${res.cfg.pose.stanceR} mm, slope ${res.cfg.env.slopeDeg}°`);
  L.push('');
  L.push(`Kitchen scale under each foot (robot standing, scale zeroed):`);
  res.contacts.forEach((c, i) => {
    const grams = (res.grf.N[i] / 9.81) * 1000;
    L.push(`  ${LEG_NAMES[c.legIdx]}: ${grams.toFixed(0)} g  (±10% is a pass)`);
  });
  L.push('');
  L.push(`Watt-meter at the XT60 (idle holding this pose):`);
  L.push(`  current ≈ ${res.power.iTotal.toFixed(2)} A, power ≈ ${res.power.watts.toFixed(1)} W, rail ≈ ${res.power.vRail.toFixed(2)} V`);
  L.push(`  runtime at this draw ≈ ${res.power.runtimeMin === Infinity ? '∞' : res.power.runtimeMin.toFixed(0)} min from ${(res.cfg.power.soc * 100).toFixed(0)}% SoC`);
  L.push('');
  L.push(`Per-leg branch current (15A blade fuses): ${res.power.legAmps.map((a, i) => `${LEG_NAMES[i]} ${a.toFixed(1)}A`).join(', ')}`);
  L.push('');
  L.push(`Worst servo: ${(() => {
    const w = res.power.perServo.reduce((a, s) => (s.utilization > a.utilization ? s : a));
    return `${LEG_NAMES[w.leg]} ${JOINT_NAMES[w.joint]} at ${w.tau.toFixed(2)} N·m = ${(w.utilization * 100).toFixed(0)}% of stall@${res.P.cutoffV}V`;
  })()}`);
  L.push('');
  L.push(`If scale readings disagree by >10%: check CoM inputs (battery/phone heights) first.`);
  L.push(`If current disagrees: servo idle draw + friction are the usual suspects — recalibrate idleA.`);
  return L.join('\n');
}

export function downloadText(filename, text) {
  const blob = new Blob([text], { type: 'text/plain' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
  URL.revokeObjectURL(a.href);
}
